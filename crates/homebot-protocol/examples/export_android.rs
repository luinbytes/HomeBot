fn main() -> Result<(), Box<dyn std::error::Error>> {
    let destination = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../android/protocol/src/main/kotlin/dev/homebot/protocol/ProtocolV1.kt");
    if env::args().any(|argument| argument == "--check") {
        if fs::read_to_string(&destination)? != GENERATED {
            return Err("Android protocol binding is stale; regenerate it".into());
        }
    } else {
        if let Some(parent) = destination.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(destination, GENERATED)?;
    }
    Ok(())
}
